"""Arrange the Unity-exported Comet Garden sprites into a review sheet."""

from pathlib import Path
import random

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SPRITES = ROOT / "docs" / "comet-garden-sprites"
OUTPUT = ROOT / "docs" / "comet-garden-runtime.png"
FONT = "/System/Library/Fonts/Helvetica.ttc"

OBJECTS = [
    ("headquarters", "SEED CITADEL", "orbital greenhouse"),
    ("extractor", "MOONSTONE GATHERER", "crystal harvest"),
    ("refinery", "STARDUST DISTILLERY", "petal condensers"),
    ("assembler", "PETAL FORGE", "living fabrication"),
    ("sale_depot", "COURIER PORT", "weightless trade"),
    ("shipyard", "NEST DOCK", "craft nursery"),
    ("storage", "CONSTELLATION PANTRY", "seedpod storage"),
    ("fort", "MOONSHIELD", "gentle defense"),
    ("tank", "ROVER", "ground craft"),
    ("artillery", "COMET MORTAR", "ranged craft"),
    ("guard", "HALO KEEPER", "shield craft"),
    ("strike", "MOTH SKIPPER", "fast craft"),
]


def font(size):
    return ImageFont.truetype(FONT, size)


def main():
    width, height = 1490, 1135
    sheet = Image.new("RGBA", (width, height), "#160e28")
    draw = ImageDraw.Draw(sheet)
    rng = random.Random(103)
    for _ in range(185):
        x, y = rng.randrange(width), rng.randrange(height)
        radius = rng.choice((1, 1, 1, 2))
        draw.ellipse((x-radius, y-radius, x+radius, y+radius), fill=rng.choice(("#503b6b", "#785787", "#a47ca1")))

    draw.ellipse((1200, 0, 1590, 300), outline="#51446b", width=2)
    draw.ellipse((-110, 830, 300, 1210), outline="#51446b", width=2)
    draw.text((58, 30), "COMET GARDEN", font=font(48), fill="#ffeadb")
    draw.text((61, 91), "A new orbital nursery world  /  actual sprites generated by the game", font=font(18), fill="#b9a8ce")
    draw.line((60, 136, 1430, 136), fill="#725c8c", width=2)

    card_w, card_h, gap, left, top = 330, 286, 20, 55, 160
    for index, (name, title, description) in enumerate(OBJECTS):
        row, col = divmod(index, 4)
        x, y = left + col * (card_w + gap), top + row * (card_h + gap)
        draw.rounded_rectangle((x, y, x+card_w, y+card_h), radius=24, fill="#241a3d", outline="#7f688d", width=2)
        draw.ellipse((x+73, y+23, x+257, y+207), fill="#302849", outline="#c990a0", width=2)
        draw.arc((x+62, y+17, x+268, y+213), 215, 322, fill="#f1c7a4", width=2)
        draw.arc((x+62, y+17, x+268, y+213), 35, 140, fill="#8fe4ca", width=2)
        draw.ellipse((x+74, y+55, x+80, y+61), fill="#ffe19d")
        draw.ellipse((x+250, y+169, x+256, y+175), fill="#ffe19d")

        sprite = Image.open(SPRITES / f"{name}.png").convert("RGBA")
        scale = 1 if name == "headquarters" else 2 if row < 2 else 3
        sprite = sprite.resize((sprite.width*scale, sprite.height*scale), Image.Resampling.NEAREST)
        sheet.alpha_composite(sprite, (x+(card_w-sprite.width)//2, y+19+(190-sprite.height)//2))

        draw.text((x+20, y+218), title, font=font(19), fill="#fff1e7")
        draw.text((x+20, y+250), description, font=font(13), fill="#bdb0d1")

    draw.text((57, 1092), "MOONSTONE  •  MINT AURORA  •  PEACH SOLAR SAILS  •  GOLDEN STARLIGHT", font=font(15), fill="#c6a5b7")
    sheet.convert("RGB").save(OUTPUT, optimize=True)
    print(OUTPUT)


if __name__ == "__main__":
    main()
